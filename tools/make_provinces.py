#!/usr/bin/env python3
"""Cut the Dutch provinces out of Natural Earth and emit the weather's
provinces.h: each province's outline, coarse, and the code KNMI's warnings
carry for it on MeteoAlarm, so the panel can tell which warnings are for home.

    tools/make_provinces.py --out components/weather/provinces.h
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_map import load, rings, simplify  # noqa: E402

SOURCE = "10m/cultural/ne_10m_admin_1_states_provinces.json"
TOLERANCE_DEG = 0.01  # about a kilometre: a province's edge within the streets of a border town

# MeteoAlarm's EMMA_ID for each province, as its feed for the Netherlands names them.
EMMA = {
    "Groningen": "NL007", "Flevoland": "NL008", "Zuid-Holland": "NL009", "Zeeland": "NL010",
    "Noord-Holland": "NL011", "Limburg": "NL012", "Noord-Brabant": "NL013", "Gelderland": "NL014",
    "Utrecht": "NL015", "Overijssel": "NL016", "Friesland": "NL017", "Drenthe": "NL018",
}
SPELLINGS = {"Fryslân": "Friesland", "Frisia": "Friesland", "North Holland": "Noord-Holland",
             "South Holland": "Zuid-Holland", "North Brabant": "Noord-Brabant"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    parser.add_argument("--cache", default=".map-cache")
    args = parser.parse_args()

    data = load(SOURCE, args.cache)
    shapes = []
    for feature in data["features"]:
        props = feature["properties"]
        if props.get("adm0_a3") != "NLD":
            continue
        name = SPELLINGS.get(props.get("name"), props.get("name"))
        if name not in EMMA:
            continue
        for shape in rings(feature["geometry"]):
            outer = simplify([tuple(p[:2]) for p in shape[0]], TOLERANCE_DEG)
            if len(outer) >= 4:
                shapes.append((name, outer))
    found = {name for name, _ in shapes}
    if found != set(EMMA):
        sys.exit(f"provinces missing: {sorted(set(EMMA) - found)}")

    lines = ["// Generated by tools/make_provinces.py -- do not edit.",
             f"// Natural Earth, public domain. {len(shapes)} outlines of the {len(EMMA)} provinces.",
             "", "#pragma once", "", "#include <cstdint>", "", "namespace weather {", "",
             "struct Province {",
             "    const char         *emma;    // MeteoAlarm's code for it",
             "    const std::int32_t *points;  // lat, lon pairs in micro-degrees, one closed ring",
             "    std::uint16_t       count;",
             "};", ""]
    for i, (name, outer) in enumerate(shapes):
        values = ",".join(f"{round(lat * 1e6)},{round(lon * 1e6)}" for lon, lat in outer)
        lines.append(f"inline constexpr std::int32_t kProvince{i}[] = {{{values}}};  // {name}")
    lines += ["", "inline constexpr Province kProvinces[] = {"]
    for i, (name, outer) in enumerate(shapes):
        lines.append(f'    {{"{EMMA[name]}", kProvince{i}, {len(outer)}}},')
    lines += ["};", f"inline constexpr int kProvinceCount = {len(shapes)};", "", "}  // namespace weather", ""]
    with open(args.out, "w") as out:
        out.write("\n".join(lines))
    print(f"{len(shapes)} outlines, {sum(len(o) for _, o in shapes)} points")


if __name__ == "__main__":
    main()
